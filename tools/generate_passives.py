"""Regenerate the companion passive catalog from Patch 8 retail Data/*.pak files."""

import argparse
import re
from pathlib import Path
from xml.etree import ElementTree as ET

from bg3forge.pak.reader import PakReader
from bg3forge.parsers.stats import StatsCollection


MODULES = {
    "Shared": ("Shared", "SharedDev"),
    "Gustav": ("Gustav", "GustavDev"),
    "GustavX": ("GustavX",),
}
GOALS = next((Path(__file__).resolve().parents[1] / "mod/Mods").glob("TacticianAI_*/Story/RawFiles/Goals"))
SELECTOR = re.compile(r"\b(?:Select|Replace)Passives\(\s*([\w-]+)")


def rows(pak, path, kind):
    if path in pak:
        for node in ET.fromstring(pak.read(path)).iterfind(f".//node[@id='{kind}']"):
            yield {a.attrib["id"]: a.get("value", "") for a in node.findall("attribute")}


def collect(data_dir):
    stats = StatsCollection()
    class_tables = set()
    progressions = []
    feats = []
    lists = {}
    for archive, modules in MODULES.items():
        with PakReader(data_dir / f"{archive}.pak") as pak:
            for module in modules:
                base = f"Public/{module}"
                class_tables.update(
                    row["ProgressionTableUUID"]
                    for row in rows(pak, f"{base}/ClassDescriptions/ClassDescriptions.lsx", "ClassDescription")
                    if row.get("ProgressionTableUUID")
                )
                progressions.extend(rows(pak, f"{base}/Progressions/Progressions.lsx", "Progression"))
                feats.extend(rows(pak, f"{base}/Feats/Feats.lsx", "Feat"))
                for row in rows(pak, f"{base}/Lists/PassiveLists.lsx", "PassiveList"):
                    lists[row["UUID"]] = row.get("Passives", "").split(",")
                source = f"{base}/Stats/Generated/Data/Passive.txt"
                stats.load_text(pak.read(source).decode("utf-8-sig"), source)

    grants = feats + [row for row in progressions if row.get("TableUUID") in class_tables]
    candidates = set()
    for row in grants:
        candidates.update(row.get("PassivesAdded", "").split(";"))
        for uid in SELECTOR.findall(row.get("Selectors", "")):
            candidates.update(lists[uid])

    result = []
    for name in sorted({value.strip() for value in candidates}):
        if name not in stats:
            continue
        fields = stats.resolved(name)
        if fields.get("DisplayName") and "IsHidden" not in fields.get("Properties", "").split(";"):
            result.append(name)
    if not result:
        raise ValueError("No visible class or feat passives were found")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("data_dir", type=Path, help="BG3's Data directory containing Shared, Gustav and GustavX.pak")
    parser.add_argument("--check", action="store_true", help="Check the committed catalog without writing it")
    args = parser.parse_args()
    candidates = collect(args.data_dir)
    lines = [
        "Version 1", "SubGoalCombiner SGC_AND", "INITSECTION",
        "// Generated by tools/generate_passives.py from retail class progressions and feats.",
        *(f'DB_BTAI_PassiveCandidate("{name}");' for name in candidates),
        "KBSECTION", "EXITSECTION", "ENDEXITSECTION", 'ParentTargetEdge "Start"', "",
    ]
    catalog = GOALS / "BTAI_PassiveCatalog.txt"
    contents = "\n".join(lines)
    if args.check:
        if catalog.read_text(encoding="utf-8") != contents:
            parser.exit(1, "Passive catalog differs from retail data\n")
    else:
        catalog.write_text(contents, encoding="utf-8")
    print(f"{len(candidates)} visible class and feat passive IDs")


if __name__ == "__main__":
    main()
